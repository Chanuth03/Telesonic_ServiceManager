export interface TransactionFieldDef {
  key: string;
  label: string;
  type:
    "text" | "number" | "date" | "select" | "yesno" | "amount" | "link" | "signature" | "images";
  mandatory?: boolean;
  isB1?: boolean; // SAP B1 integration point badge
  readOnly?: boolean; // Grey calculated or system field
  options?: string[];
  placeholder?: string;
  colSpan?: 1 | 2;
  source?: string;
  validation?: string;
}

export interface TransactionTabDef {
  id: string;
  label: string;
  columns: { key: string; label: string; isB1?: boolean; align?: "left" | "right" }[];
  data: Record<string, unknown>[];
}

