export interface MasterScreenMeta {
  id: string; // e.g. "O1-SCR-MST-01"
  code: string; // e.g. "MST-01"
  name: string;
  category:
    | "Business Partners & People"
    | "Sites & Installed Base"
    | "Service Governance & SLAs"
    | "Commercial & Contracts";
  type: string;
  classification: string;
  priority: "P1" | "P2" | "P3" | "P4";
  purpose: string;
  roles: string;
  statusFlow: string;
  linkedNavigation: string[];
  fields: MasterFieldDef[];
  tabs: MasterTabDef[];
  actions: string[];
  sampleRecord: Record<string, unknown>;
}

export interface MasterFieldDef {
  key: string;
  label: string;
  type: "text" | "number" | "date" | "select" | "yesno" | "amount" | "link";
  mandatory?: boolean;
  isB1?: boolean; // SAP B1 integration point badge
  readOnly?: boolean; // Grey calculated field
  options?: string[];
  placeholder?: string;
  colSpan?: 1 | 2;
}

export interface MasterTabDef {
  id: string;
  label: string;
  columns: { key: string; label: string; isB1?: boolean; align?: "left" | "right" }[];
  data: Record<string, unknown>[];
}

