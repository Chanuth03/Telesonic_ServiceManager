import React, { useState } from "react";
import { ArrowLeft, Download, History, Info, Check, RefreshCw, FileText } from "lucide-react";
import { MasterScreenMeta } from "@/data/mastersSpecData";
import { MasterField } from "./MasterField";
import { MasterAuditModal } from "./MasterAuditModal";
import { MasterExportModal } from "./MasterExportModal";

interface MasterScreenViewProps {
  meta: MasterScreenMeta;
  onBack: () => void;
}

export const MasterScreenView: React.FC<MasterScreenViewProps> = ({ meta, onBack }) => {
  const [formData, setFormData] = useState<Record<string, any>>(meta.sampleRecord);
  const [activeTabId, setActiveTabId] = useState<string>(meta.tabs[0]?.id || "");
  const [isAuditOpen, setIsAuditOpen] = useState(false);
  const [isExportOpen, setIsExportOpen] = useState(false);
  const [showSpecDetails, setShowSpecDetails] = useState(false);
  const [saveToast, setSaveToast] = useState(false);
  const [b1Syncing, setB1Syncing] = useState(false);

  const activeTab = meta.tabs.find((t) => t.id === activeTabId) || meta.tabs[0];

  const handleFieldChange = (key: string, val: any) => {
    setFormData((prev) => ({ ...prev, [key]: val }));
  };

  const handleAction = (action: string) => {
    if (action.includes("History") || action.includes("Audit")) {
      setIsAuditOpen(true);
      return;
    }
    if (action.includes("Export")) {
      setIsExportOpen(true);
      return;
    }
    if (action.includes("B1 Change") || action.includes("Request B1")) {
      setB1Syncing(true);
      setTimeout(() => {
        setB1Syncing(false);
        alert(
          `⇄B1 Integration Request Transmitted: Change request dispatched to SAP Business One DI Server API.`,
        );
      }, 700);
      return;
    }

    // Default Save / Update
    setSaveToast(true);
    setTimeout(() => setSaveToast(false), 2500);
  };

  const handleExportExcel = () => {
    if (!activeTab) return;
    const headers = activeTab.columns.map((c) => c.label);
    const rows = activeTab.data.map((row) =>
      activeTab.columns.map((col) => `"${row[col.key] ?? ""}"`),
    );

    const reportCriteria = [
      ["# REPORT CRITERIA SHEET — TELESONIC LANKA SERVICE MANAGEMENT (OPTION 01)"],
      [`Screen ID: ${meta.id}`, `Screen Name: ${meta.name}`],
      [
        `Active Record: ${formData[meta.fields[0]?.key] || "N/A"}`,
        `Generated By: Kasun Perera (Service Coordinator)`,
      ],
      [`Timestamp: ${new Date().toISOString()}`, `Confidentiality: Internal Telesonic Sri Lanka`],
      ["--------------------------------------------------"],
      [],
    ];

    const csvContent =
      "data:text/csv;charset=utf-8," +
      reportCriteria.map((r) => r.join(",")).join("\n") +
      "\n" +
      headers.join(",") +
      "\n" +
      rows.map((r) => r.join(",")).join("\n");

    const encodedUri = encodeURI(csvContent);
    const link = document.createElement("a");
    link.setAttribute("href", encodedUri);
    link.setAttribute("download", `${meta.code.toLowerCase()}_${activeTab.id}_export.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handleExportPdf = () => {
    window.print();
  };

  return (
    <div className="space-y-4">
      {/* Top Banner & Breadcrumbs */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 pb-2 border-b border-neutral-200 dark:border-neutral-800">
        <div className="flex items-center gap-3">
          <button
            onClick={onBack}
            className="p-1.5 rounded-md hover:bg-neutral-100 dark:hover:bg-neutral-800 text-neutral-600 dark:text-neutral-400 transition-colors cursor-pointer flex items-center gap-1 text-xs"
            title="Return to Masters Hub"
          >
            <ArrowLeft className="w-4 h-4" />
            <span className="hidden sm:inline">Back to Masters Hub</span>
          </button>
          <div className="h-4 w-px bg-neutral-200 dark:bg-neutral-800" />
          <span className="text-[11px] font-mono text-neutral-400 uppercase tracking-wider">
            Masters · {meta.category}
          </span>
        </div>

        <div className="flex items-center gap-3 text-xs text-neutral-500">
          <span className="font-mono text-[11px]">User: Kasun Perera · Service Coordinator</span>
          <button
            onClick={() => setShowSpecDetails(!showSpecDetails)}
            className="flex items-center gap-1 text-primary hover:underline text-xs cursor-pointer font-medium"
          >
            <Info className="w-3.5 h-3.5" />
            <span>{showSpecDetails ? "Hide Spec Sheet" : "PDF Specification Details"}</span>
          </button>
        </div>
      </div>

      {/* Specification Reference Sheet (collapsible) */}
      {showSpecDetails && (
        <div className="p-4 bg-sky-50/60 dark:bg-sky-950/30 border border-sky-200 dark:border-sky-900 rounded-lg text-xs space-y-2 text-neutral-800 dark:text-neutral-200">
          <div className="flex items-center justify-between font-bold text-sky-900 dark:text-sky-300">
            <span>Section A3 Specification Sheet: {meta.id}</span>
            <span className="font-mono text-[11px]">Classification: {meta.classification}</span>
          </div>
          <p>
            <span className="font-semibold">Purpose:</span> {meta.purpose}
          </p>
          <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-4 gap-2 text-[11px] pt-1">
            <div>
              <span className="text-neutral-500">Authorized Roles:</span> {meta.roles}
            </div>
            <div>
              <span className="text-neutral-500">Status Flow:</span> {meta.statusFlow}
            </div>
            <div>
              <span className="text-neutral-500">Priority:</span> {meta.priority}
            </div>
            <div>
              <span className="text-neutral-500">Linked Navigation:</span>{" "}
              {meta.linkedNavigation.join(", ")}
            </div>
          </div>
        </div>
      )}

      {/* Main Wireframe Screen Card */}
      <div className="bg-white dark:bg-[#111722] border border-neutral-200 dark:border-neutral-800 rounded-lg shadow-sm overflow-hidden">
        {/* Sample Screen Title Bar */}
        <div className="px-5 py-3 border-b border-neutral-200 dark:border-neutral-800 bg-neutral-50/70 dark:bg-neutral-900/60 flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-3">
            <h1 className="text-sm font-bold text-neutral-900 dark:text-neutral-100 flex items-center gap-2">
              <span>{meta.name}</span>
              <span className="text-xs font-mono font-normal text-neutral-400">({meta.id})</span>
            </h1>
            <span className="inline-flex items-center px-2 py-0.5 rounded-full text-[11px] font-semibold bg-emerald-100 text-emerald-800 dark:bg-emerald-950/80 dark:text-emerald-300 border border-emerald-300 dark:border-emerald-800">
              {formData.status || "Active"}
            </span>
          </div>

          {/* Action Table Buttons */}
          <div className="flex flex-wrap items-center gap-1.5">
            {meta.actions.map((act) => (
              <button
                key={act}
                onClick={() => handleAction(act)}
                disabled={b1Syncing}
                className="px-2.5 py-1 text-xs font-medium rounded-md border border-neutral-300 dark:border-neutral-700 bg-white dark:bg-neutral-800 text-neutral-800 dark:text-neutral-200 hover:bg-neutral-50 dark:hover:bg-neutral-700 transition-colors shadow-2xs cursor-pointer disabled:opacity-50"
              >
                {act === "History / Audit" ? (
                  <span className="flex items-center gap-1">
                    <History className="w-3 h-3" />
                    <span>Audit Log</span>
                  </span>
                ) : act === "Export Excel / PDF" ? (
                  <span className="flex items-center gap-1">
                    <Download className="w-3 h-3" />
                    <span>Export</span>
                  </span>
                ) : act === "Request B1 Change" ? (
                  <span className="flex items-center gap-1 text-sky-600 dark:text-sky-400 font-semibold">
                    <RefreshCw className={`w-3 h-3 ${b1Syncing ? "animate-spin" : ""}`} />
                    <span>Request B1 Change</span>
                  </span>
                ) : (
                  act
                )}
              </button>
            ))}
          </div>
        </div>

        {/* Success Toast */}
        {saveToast && (
          <div className="mx-5 my-2 p-2 bg-emerald-50 dark:bg-emerald-950/60 border border-emerald-300 dark:border-emerald-800 rounded text-xs text-emerald-800 dark:text-emerald-200 flex items-center gap-2">
            <Check className="w-4 h-4 text-emerald-600" />
            <span>Master record changes successfully validated and saved to local state.</span>
          </div>
        )}

        {/* Form Fields Grid */}
        <div className="p-5 grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
          {meta.fields.map((f) => (
            <MasterField
              key={f.key}
              field={f}
              value={formData[f.key]}
              onChange={(val) => handleFieldChange(f.key, val)}
            />
          ))}
        </div>

        {/* Tab Sub-Grids */}
        {meta.tabs.length > 0 && (
          <div className="border-t border-neutral-200 dark:border-neutral-800">
            {/* Tabs List */}
            <div className="flex flex-wrap items-center border-b border-neutral-200 dark:border-neutral-800 px-4 bg-neutral-50/50 dark:bg-neutral-900/40 gap-1">
              {meta.tabs.map((tab) => (
                <button
                  key={tab.id}
                  onClick={() => setActiveTabId(tab.id)}
                  className={`px-3 py-2 text-xs font-semibold border-b-2 transition-colors cursor-pointer ${
                    activeTabId === tab.id
                      ? "border-primary text-primary font-bold bg-white dark:bg-neutral-900 shadow-2xs"
                      : "border-transparent text-neutral-500 hover:text-neutral-800 dark:hover:text-neutral-200"
                  }`}
                >
                  {tab.label} ({tab.data.length})
                </button>
              ))}
            </div>

            {/* Active Tab Sub-Grid */}
            {activeTab && (
              <div className="p-4 space-y-3">
                <div className="flex items-center justify-between text-xs">
                  <div className="font-semibold text-neutral-700 dark:text-neutral-300">
                    {activeTab.label} Register
                  </div>
                  <div className="flex items-center gap-2">
                    <button
                      onClick={handleExportExcel}
                      className="px-2 py-1 text-xs font-medium rounded-md border border-neutral-300 dark:border-neutral-700 hover:bg-neutral-100 dark:hover:bg-neutral-800 text-neutral-700 dark:text-neutral-300 transition-colors cursor-pointer flex items-center gap-1"
                    >
                      <Download className="w-3 h-3" />
                      <span>Export Excel</span>
                    </button>
                    <button
                      onClick={() => setIsExportOpen(true)}
                      className="px-2 py-1 text-xs font-medium rounded-md border border-neutral-300 dark:border-neutral-700 hover:bg-neutral-100 dark:hover:bg-neutral-800 text-neutral-700 dark:text-neutral-300 transition-colors cursor-pointer flex items-center gap-1"
                    >
                      <FileText className="w-3 h-3" />
                      <span>Export PDF</span>
                    </button>
                  </div>
                </div>

                <div className="overflow-x-auto border border-neutral-200 dark:border-neutral-800 rounded-md">
                  <table className="w-full text-left border-collapse text-xs">
                    <thead>
                      <tr className="bg-neutral-100/70 dark:bg-neutral-900 border-b border-neutral-200 dark:border-neutral-800 text-neutral-600 dark:text-neutral-400">
                        {activeTab.columns.map((col) => (
                          <th
                            key={col.key}
                            className={`py-2 px-3 font-semibold ${
                              col.align === "right" ? "text-right" : "text-left"
                            }`}
                          >
                            <span className="flex items-center gap-1">
                              {col.label}
                              {col.isB1 && (
                                <span className="text-[9px] font-mono px-1 py-0.2 rounded-xs bg-sky-100 text-sky-800 dark:bg-sky-950 dark:text-sky-300">
                                  ⇄B1
                                </span>
                              )}
                            </span>
                          </th>
                        ))}
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-neutral-100 dark:divide-neutral-800/80 bg-white dark:bg-neutral-900/30">
                      {activeTab.data.length === 0 ? (
                        <tr>
                          <td
                            colSpan={activeTab.columns.length}
                            className="py-6 text-center text-neutral-400"
                          >
                            No records in this tab
                          </td>
                        </tr>
                      ) : (
                        activeTab.data.map((row, idx) => (
                          <tr
                            key={idx}
                            className="hover:bg-neutral-50/70 dark:hover:bg-neutral-800/40 transition-colors"
                          >
                            {activeTab.columns.map((col) => (
                              <td
                                key={col.key}
                                className={`py-2 px-3 text-neutral-800 dark:text-neutral-200 ${
                                  col.align === "right"
                                    ? "text-right font-mono tabular-nums"
                                    : "font-normal"
                                }`}
                              >
                                {row[col.key] || "—"}
                              </td>
                            ))}
                          </tr>
                        ))
                      )}
                    </tbody>
                  </table>
                </div>
              </div>
            )}
          </div>
        )}

        {/* Legend Footer (Section A1 Design Principles) */}
        <div className="px-5 py-2.5 bg-neutral-50 dark:bg-neutral-950 border-t border-neutral-200 dark:border-neutral-800 text-[11px] text-neutral-500 flex flex-wrap items-center justify-between gap-4 font-mono">
          <div className="flex flex-wrap items-center gap-4">
            <span className="flex items-center gap-1">
              <span className="px-1 py-0.2 rounded-xs bg-sky-100 text-sky-800 dark:bg-sky-950 dark:text-sky-300 border border-sky-300 dark:border-sky-800 text-[10px]">
                ⇄B1
              </span>
              <span>SAP B1 Integration Point</span>
            </span>
            <span className="flex items-center gap-1">
              <span className="w-3 h-3 rounded-xs bg-neutral-100 dark:bg-neutral-800 border border-neutral-300 dark:border-neutral-700" />
              <span>Calculated / Read-only Field</span>
            </span>
            <span className="flex items-center gap-1">
              <span className="text-red-500 font-bold">*</span>
              <span>Mandatory Field</span>
            </span>
          </div>
        </div>
      </div>

      {/* Audit Modal */}
      <MasterAuditModal
        isOpen={isAuditOpen}
        onClose={() => setIsAuditOpen(false)}
        recordId={formData[meta.fields[0]?.key] || meta.code}
        screenTitle={meta.name}
      />

      {/* Export Modal */}
      {activeTab && (
        <MasterExportModal
          isOpen={isExportOpen}
          onClose={() => setIsExportOpen(false)}
          meta={meta}
          activeTab={activeTab}
          formData={formData}
        />
      )}
    </div>
  );
};
